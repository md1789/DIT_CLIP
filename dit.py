class DiT(nn.Module):
    """
    Diffusion Transformer (DiT) model.
    """
    def __init__(self, img_size=32, patch_size=4, in_chans=3, hidden_size=384, depth=4, num_heads=6, mlp_ratio=4.0):
        super().__init__()
        self.out_channels = in_chans
        self.img_size = img_size
        self.patch_size = patch_size

        self.patch_embed = PatchEmbed(img_size, patch_size, in_chans, hidden_size)
        self.num_patches = self.patch_embed.num_patches

        # Learnable position embedding
        self.pos_embed = nn.Parameter(torch.zeros(1, self.num_patches, hidden_size), requires_grad=False)
        self.t_embedder = TimestepEmbedder(hidden_size)

        self.blocks = nn.ModuleList([
            DiTBlock(hidden_size, num_heads, mlp_ratio=mlp_ratio) for _ in range(depth)
        ])

        self.final_layer = FinalLayer(hidden_size, patch_size, self.out_channels)
        self.initialize_weights()

    def initialize_weights(self):
        # Initialize transformer layers
        def _init_weights(m):
            if isinstance(m, nn.Linear):
                torch.nn.init.xavier_uniform_(m.weight)
                if m.bias is not None:
                    nn.init.constant_(m.bias, 0)
        self.apply(_init_weights)

        # Initialize timestep embedding MLP
        nn.init.normal_(self.t_embedder.mlp[0].weight, std=0.02)
        nn.init.normal_(self.t_embedder.mlp[2].weight, std=0.02)

        # Zero-out adaLN modulation layers
        for block in self.blocks:
            nn.init.constant_(block.adaLN_modulation[-1].weight, 0)
            nn.init.constant_(block.adaLN_modulation[-1].bias, 0)

        nn.init.constant_(self.final_layer.adaLN_modulation[-1].weight, 0)
        nn.init.constant_(self.final_layer.adaLN_modulation[-1].bias, 0)
        nn.init.constant_(self.final_layer.linear.weight, 0)
        nn.init.constant_(self.final_layer.linear.bias, 0)

    def unpatchify(self, x):
        """
        x: (N, L, patch_size**2 * out_channels)
        imgs: (N, out_channels, H, W)
        """
        p = self.patch_size
        c = self.out_channels
        h = w = self.img_size // p

        x = rearrange(x, 'n (h w) (p1 p2 c) -> n c (h p1) (w p2)', h=h, w=w, p1=p, p2=p, c=c)
        return x

    def forward(self, x, t):
        # x: (N, C, H, W)
        # t: (N,)
        x = self.patch_embed(x) + self.pos_embed
        c = self.t_embedder(t)

        for block in self.blocks:
            x = block(x, c)

        x = self.final_layer(x, c)
        x = self.unpatchify(x)
        return x

