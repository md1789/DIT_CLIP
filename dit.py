    img = torch.randn(shape, device=device)

    for i in reversed(range(0, timesteps)):
        t = torch.full((b,), i, device=device, dtype=torch.long)

        # Enable gradients for guidance
        with torch.enable_grad():
            img = img.detach().requires_grad_(True)
            model_output = model(img, t)

            # Estimate x_0
            sqrt_alpha_t = extract(sqrt_alphas_cumprod, t, img.shape)
            sqrt_one_minus_alpha_t = extract(sqrt_one_minus_alphas_cumprod, t, img.shape)
            x_0_pred = (img - sqrt_one_minus_alpha_t * model_output) / sqrt_alpha_t

            # CLIP Guidance Loss
            clip_in = process_for_clip(x_0_pred)
            image_embed = clip_model.encode_image(clip_in)
            image_embed = image_embed / image_embed.norm(dim=1, keepdim=True)
            loss = -(image_embed * text_embed).sum()

            grads = torch.autograd.grad(loss, img)[0]

        # Reverse Diffusion Step
        betas_t = extract(betas, t, img.shape)
        sqrt_recip_alphas_t = extract(torch.sqrt(1.0 / alphas), t, img.shape)
        sqrt_one_minus_alphas_cumprod_t = extract(sqrt_one_minus_alphas_cumprod, t, img.shape)
        posterior_variance_t = extract(posterior_variance, t, img.shape)

        # Mean without guidance
        model_mean = sqrt_recip_alphas_t * (img - betas_t * model_output.detach() / sqrt_one_minus_alphas_cumprod_t)

        # Apply Guidance
        guided_mean = model_mean - posterior_variance_t * guidance_scale * grads

        if i > 0:
            noise = torch.randn_like(img)
            img = guided_mean + torch.sqrt(posterior_variance_t) * noise
        else:
            img = guided_mean

        img = img.detach()

    return img

