def p_sample_loop(model, shape, timesteps, intermediate_timesteps=None):
    """Full reverse diffusion sampling loop, with intermediate sample saving."""
    device = next(model.parameters()).device
    b = shape[0]
    img = torch.randn(shape, device=device)

    intermediate_samples = {}
    if intermediate_timesteps is None:
        intermediate_timesteps = []

    # Sort in descending order to ensure `i` matches `t_index` in p_sample
    sorted_intermediate_timesteps = sorted([t for t in intermediate_timesteps if t < timesteps], reverse=True)

    for i in reversed(range(0, timesteps)):
        t = torch.full((b,), i, device=device, dtype=torch.long)
        img = p_sample(model, img, t, i)

        if i in sorted_intermediate_timesteps:
            intermediate_samples[i] = img.cpu().clone()

    return img, intermediate_samples

